export const formatRupiah = (n: number) =>
  new Intl.NumberFormat("id-ID", {
    style: "currency",
    currency: "IDR",
    minimumFractionDigits: 0,
    maximumFractionDigits: 0,
  }).format(n);

export const discountPercent = (p: Product) => {
  if (!p.priceOriginal || p.priceOriginal <= p.price) return 0;
  return Math.round(((p.priceOriginal - p.price) / p.priceOriginal) * 100);
};

export const getProductBySlug = (slug: string) => PRODUCTS.find((p) => p.slug === slug);

export const getProductsByCategory = (category: CategoryKey) =>
  PRODUCTS.filter((p) => p.category === category);

export const searchProducts = (query: string, category?: CategoryKey) => {
  const q = query.trim().toLowerCase();
  return PRODUCTS.filter((p) => {
    const matchCategory = category ? p.category === category : true;
    const matchQuery = q ? p.name.toLowerCase().includes(q) : true;
    return matchCategory && matchQuery;
  });
};

export const getCategory = (key: CategoryKey) => CATEGORIES.find((c) => c.key === key);

export const relatedProducts = (p: Product, count = 4) =>
  PRODUCTS.filter((x) => x.category === p.category && x.id !== p.id).slice(0, count);

